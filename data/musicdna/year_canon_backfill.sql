scored AS (
  SELECT
    s.id,
    LEAST(
      100,
      GREATEST(
        0,
        COALESCE(
          e.score,
          lb.base_score + ((abs(hashtext(s.artist || '|' || s.title || '|' || s.lane)) % 17) - 8)
        )
      )
    )::integer AS score
  FROM public.songs AS s
  LEFT JOIN explicit_score AS e
    ON e.artist = s.artist
   AND e.title = s.title
  LEFT JOIN lane_base AS lb
    ON lb.lane = s.lane
  WHERE s.active = true
    AND s.canon_score IS NULL
    AND lb.base_score IS NOT NULL
)
